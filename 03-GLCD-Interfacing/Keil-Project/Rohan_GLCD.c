void delay(unsigned int t)
{
    unsigned int i, j;
    for(i = 0; i < t; i++)
        for(j = 0; j < 100; j++);
}

void selectLeft(void)
{
    IO1CLR = CS1;
    IO1SET = CS2;
}

void selectRight(void)
{
    IO1SET = CS1;
    IO1CLR = CS2;
}

void GLCD_Command(unsigned char cmd)
{
    IO1CLR = RS | RW;
    IO0CLR = DATA_MASK;
    IO0SET = ((unsigned long)cmd << 16);

    IO1SET = EN;
    delay(1);
    IO1CLR = EN;
    delay(1);
}

void GLCD_Data(unsigned char data)
{
    IO1SET = RS;
    IO1CLR = RW;
    IO0CLR = DATA_MASK;
    IO0SET = ((unsigned long)data << 16);

    IO1SET = EN;
    delay(1);
    IO1CLR = EN;
    delay(1);
}

void GLCD_Init(void)
{
    PINSEL1 &= ~0x0000FFFFUL;

    IO0DIR |= DATA_MASK;
    IO1DIR |= CS1 | CS2 | EN | RW | RS | RST;

    IO1SET = CS1 | CS2 | EN | RW | RS | RST;
    delay(100);

    IO1CLR = RST;
    delay(100);
    IO1SET = RST;
    delay(100);

    selectLeft();
    GLCD_Command(0x3F);
    GLCD_Command(0xC0);

    selectRight();
    GLCD_Command(0x3F);
    GLCD_Command(0xC0);
}

void GLCD_Clear(void)
{
    unsigned int page, col;

    for(page = 0; page < 8; page++)
    {
        selectLeft();
        GLCD_Command(0xB8 | page);
        GLCD_Command(0x40);

        for(col = 0; col < 64; col++)
            GLCD_Data(0x00);

        selectRight();
        GLCD_Command(0xB8 | page);
        GLCD_Command(0x40);

        for(col = 0; col < 64; col++)
            GLCD_Data(0x00);
    }
}

void clearBuffer(void)
{
    unsigned int page, x;

    for(page = 0; page < 8; page++)
        for(x = 0; x < 128; x++)
            buffer[page][x] = 0x00;
}

void setPixel(int x, int y)
{
    if(x >= 0 && x < 128 && y >= 0 && y < 64)
        buffer[y / 8][x] |= (1U << (y % 8));
}

void drawBat(void)
{
    unsigned int x, y;
    unsigned char mask;

    for(y = 0; y < 43; y++)
    {
        for(x = 0; x < 116; x++)
        {
            mask = 0x80 >> (x % 8);

            if(batBitmap[y][x / 8] & mask)
                setPixel(x + 6, y + 10);
        }
    }
}

void displayBuffer(void)
{
    unsigned int page, x;

    for(page = 0; page < 8; page++)
    {
        selectLeft();
        GLCD_Command(0xB8 | page);
        GLCD_Command(0x40);

        for(x = 0; x < 64; x++)
            GLCD_Data(buffer[page][x]);

        selectRight();
        GLCD_Command(0xB8 | page);
        GLCD_Command(0x40);

        for(x = 64; x < 128; x++)
            GLCD_Data(buffer[page][x]);
    }
}

int main(void)
{
    GLCD_Init();
    GLCD_Clear();

    clearBuffer();
    drawBat();
    displayBuffer();

    while(1);
}
